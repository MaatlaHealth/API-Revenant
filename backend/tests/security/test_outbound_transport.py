def test_connects_to_validated_ip_without_second_dns_lookup(
    http_server: _Server, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Real connector, real sockets. Any OS-level lookup of a non-literal host fails the test."""
    lookups: list[str] = []
    original = socket.getaddrinfo

    def spy(host, *args, **kwargs):  # type: ignore[no-untyped-def]
        text = host.decode() if isinstance(host, bytes) else host
        try:
            ipaddress.ip_address(text)
        except (ValueError, TypeError):
            lookups.append(str(text))
            raise socket.gaierror(f"unexpected DNS lookup of {text!r}")
        return original(host, *args, **kwargs)

    monkeypatch.setattr(socket, "getaddrinfo", spy)
    resolver = StubResolver(["127.0.0.1"])
    backend = GuardedBackend(policy=LOOPBACK_ALLOWED, resolver=resolver, connector=real_connector)

    async def go() -> int:
        async with build_client(backend) as client:
            return (await client.get(f"http://{HOSTNAME}:{http_server.port}/")).status_code
    assert run(go()) == 200
    assert lookups == []                               # the hostname never reached the OS resolver
    assert len(resolver.calls) == 1                    # exactly one resolution, ours
    assert backend.dialled == [(HOSTNAME, "127.0.0.1", http_server.port)]
    assert http_server.hits[0][1] == f"{HOSTNAME}:{http_server.port}"



"""``RuntimeProxy``: the legacy interface, served by a compiled adapter
(docs/architecture.md, sections 4.6 and 4.7).

One ASGI application, reached by path (``/runtime/{slug}/...``) or by host.
Both entries converge on ``_serve``. The request path reads only in-memory
state: no database access happens here.
"""


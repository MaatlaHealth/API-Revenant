class _Handler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def do_GET(self) -> None:  # noqa: N802
        self.server.hits.append((self.path, self.headers.get("Host")))  # type: ignore[attr-defined]
        if self.path.startswith("/redirect"):
            target = self.server.redirect_to  # type: ignore[attr-defined]
            self.send_response(302)
            self.send_header("Location", target)
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        body = b"ok"
        self.send_response(200)
        self.send_header("Content-Length", str(len(body)))
        if self.path.startswith("/close"):
            self.send_header("Connection", "close")
            self.close_connection = True
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args: object) -> None:
        pass


class _Server(http.server.ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, tls: ssl.SSLContext | None = None) -> None:
        super().__init__(("127.0.0.1", 0), _Handler)
        self.hits: list[tuple[str, str | None]] = []
        self.redirect_to = "http://169.254.169.254/latest/meta-data/"
        self.sni_seen: list[str | None] = []
        self.accepted = 0
        if tls is not None:
            tls.sni_callback = lambda _sock, name, _ctx: self.sni_seen.append(name)
            self.socket = tls.wrap_socket(self.socket, server_side=True)

    @property
    def port(self) -> int:
        return self.server_address[1]

    def get_request(self):  # type: ignore[no-untyped-def]
        result = super().get_request()
        self.accepted += 1
        return result

    def handle_error(self, request: object, client_address: object) -> None:
        pass  # failed TLS handshakes are expected in negative tests


def _serve(server: _Server) -> Iterator[_Server]:
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield server
    finally:
        server.shutdown()
        server.server_close()



"""Keep the application's outbound transport tests identical to the spike's.

``backend/tests/security/test_outbound_transport.py`` is generated from
``spikes/outbound_transport/test_guarded_transport.py`` by a mechanical rename.
That way the application module is held to exactly the cases that passed the
Linux CI gate, and nobody can quietly edit a case in one place only.

    python tools/sync_outbound_tests.py            regenerate the file
    python tools/sync_outbound_tests.py --check    exit 1 if it has drifted (used by CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "spikes" / "outbound_transport" / "test_guarded_transport.py"
TARGET = ROOT / "backend" / "tests" / "security" / "test_outbound_transport.py"

REPLACEMENTS: list[tuple[str, str]] = [
    (
        '"""Executable evidence for the outbound-transport feasibility spike.\n\n'
        "Run:  pytest spikes/outbound_transport -v\n",
        '"""Outbound transport tests for ``revenant.security.outbound``.\n\n'
        "GENERATED by tools/sync_outbound_tests.py from the spike's test file. Do not\n"
        "edit by hand: change the spike test and regenerate, so both stay identical.\n"
        "These are the cases that passed on Linux and Windows in CI before the\n"
        "transport was accepted as an application dependency.\n\n"
        "Run:  pytest tests/security/test_outbound_transport.py -v\n",
    ),
    (
        "from guarded_transport import (\n"
        "    GuardedBackend,\n"
        "    OutboundBlocked,\n"
        "    OutboundPolicy,\n"
        "    build_client,\n"
        "    real_connector,\n"
        ")\n",
        "from revenant.security.outbound import (\n"
        "    GuardedBackend,\n"
        "    OutboundBlocked,\n"
        "    OutboundPolicy,\n"
        "    real_connector,\n"
        ")\n"
        "from revenant.security.outbound import build_outbound_client as build_client\n",
    ),
    # The application transport translates httpcore errors into httpx errors.
    (
        "with pytest.raises(httpcore.ConnectError) as excinfo:",
        "with pytest.raises(httpx.ConnectError) as excinfo:",
    ),
    (
        "                with pytest.raises(httpcore.ConnectError):\n"
        '                    await client.get(f"https://{HOSTNAME}:{server.port}/")',
        "                with pytest.raises(httpx.ConnectError):\n"
        '                    await client.get(f"https://{HOSTNAME}:{server.port}/")',
    ),
]


def generate() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    for old, new in REPLACEMENTS:
        if text.count(old) != 1:
            raise SystemExit(f"expected exactly one occurrence in the spike test of:\n{old}")
        text = text.replace(old, new)
    return text


def main() -> int:
    expected = generate()
    if "--check" in sys.argv[1:]:
        actual = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if actual != expected:
            print(f"{TARGET.relative_to(ROOT)} has drifted from the spike test.")
            print("Run: python tools/sync_outbound_tests.py")
            return 1
        print(f"{TARGET.relative_to(ROOT)} matches the spike test "
              f"({expected.count(chr(10) + 'def test_')} test functions).")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

import asyncio
import base64
import json
import time
import uuid
from dataclasses import dataclass, field
from datetime import UTC, datetime
from typing import Any
from urllib.parse import parse_qsl, quote, unquote, unquote_plus

import httpx
import structlog

from revenant.adapter.compiler import find_route
from revenant.adapter.document import AdapterDocument
from revenant.config import Settings
from revenant.errors import OutboundBlocked
